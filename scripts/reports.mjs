import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
const write = (file, text) => fs.writeFileSync(file, text, 'utf8');
const assert = (condition, message) => { if (!condition) throw new Error(message); };
function validDate(value) { return /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0,10) === value; }
function asset(value, folder) {
  assert(typeof value === 'string' && value.trim(), '媒体路径不能为空');
  if (/^https:\/\//.test(value)) { new URL(value); return; }
  assert(!/^[a-z]+:|^[/\\]/i.test(value), `不支持的媒体路径：${value}`);
  const target = path.resolve(folder, value);
  assert(target.startsWith(root + path.sep) && fs.existsSync(target) && fs.statSync(target).isFile(), `媒体文件不存在或超出仓库：${value}`);
}
function validate(data, folder) {
  assert(validDate(data.date) && path.basename(folder) === data.date, `日期与目录不匹配：${folder}`);
  assert(typeof data.title === 'string' && data.title.trim(), `${data.date} 缺少标题`);
  assert(typeof data.summary === 'string' && Array.isArray(data.tags) && data.tags.every(t=>typeof t === 'string'), `${data.date} 摘要或标签格式错误`);
  assert(['legacy','standard'].includes(data.layout), '未知页面类型');
  assert(fs.existsSync(path.join(folder,'index.html')), `${data.date} 缺少 index.html`);
  if (data.layout === 'legacy') {
    const context = {window:{}};
    vm.runInNewContext(fs.readFileSync(path.join(folder,'content.js'),'utf8'), context, {timeout:1000});
    for (const videos of Object.values(context.window.REPORT.groups)) for (const v of videos) { asset(v.src,folder); if(v.poster) asset(v.poster,folder); }
    for (const match of fs.readFileSync(path.join(folder,'app.js'),'utf8').matchAll(/(?:src|href)="(media\/[^"$]+)"/g)) asset(match[1],folder);
    return;
  }
  assert(Array.isArray(data.sections) && data.sections.length, '至少需要一个章节');
  const ids = new Set();
  for (const s of data.sections) {
    assert(/^[a-z][a-z0-9-]*$/.test(s.id) && !ids.has(s.id), `章节 id 无效或重复：${s.id}`); ids.add(s.id);
    assert(typeof s.title === 'string' && s.title.trim() && Array.isArray(s.blocks), '章节格式错误');
    for (const b of s.blocks) {
      assert(['text','bullets','image','videos','metrics','table'].includes(b.type), `未知内容类型：${b.type}`);
      if (b.type === 'text') assert(typeof b.text === 'string','text 必须是文字');
      if (b.type === 'bullets') assert(Array.isArray(b.items) && b.items.every(v=>typeof v==='string'), 'bullets.items 必须是文字数组');
      if (b.type === 'image') asset(b.src,folder);
      if (b.type === 'videos') { assert(Array.isArray(b.items),'videos.items 必须是数组'); for(const v of b.items) { assert(typeof v.title==='string','视频缺少标题'); asset(v.src,folder); if(v.poster) asset(v.poster,folder); } }
      if (b.type === 'metrics') assert(Array.isArray(b.items) && b.items.every(v=>typeof v.label==='string' && ['string','number'].includes(typeof v.value)), 'metrics 格式错误');
      if (b.type === 'table') assert(Array.isArray(b.columns) && b.columns.every(v=>typeof v==='string') && Array.isArray(b.rows) && b.rows.every(r=>Array.isArray(r) && r.length===b.columns.length && r.every(v=>['string','number'].includes(typeof v))), 'table 列数或内容格式错误');
    }
  }
}
function collect() {
  return fs.readdirSync(path.join(root,'reports'), {withFileTypes:true}).filter(d=>d.isDirectory()).map(d=>{
    const folder = path.join(root,'reports',d.name), data = read(path.join(folder,'report.json')); validate(data,folder); return {data,folder};
  }).sort((a,b)=>b.data.date.localeCompare(a.data.date));
}
function build() {
  const reports = collect();
  for (const {data,folder} of reports) if(data.layout === 'standard') write(path.join(folder,'content.js'),'// Generated from report.json.\nwindow.WEEKLY_REPORT = '+JSON.stringify(data,null,2)+';\n');
  write(path.join(root,'reports.js'), '// Generated by npm run build.\nwindow.REPORT_INDEX = '+JSON.stringify(reports.map(({data})=>({date:data.date,title:data.title,summary:data.summary,tags:data.tags,url:`reports/${data.date}/`})),null,2)+';\n');
  console.log(`已生成目录：${reports.length} 份汇报`);
}
function check() {
  const reports=collect();
  const expected=reports.map(({data})=>({date:data.date,title:data.title,summary:data.summary,tags:data.tags,url:`reports/${data.date}/`}));
  const context={window:{}}; vm.runInNewContext(fs.readFileSync(path.join(root,'reports.js'),'utf8'),context,{timeout:1000});
  assert(JSON.stringify(context.window.REPORT_INDEX)===JSON.stringify(expected),'目录未更新，请先 npm run build');
  for(const {data,folder} of reports) if(data.layout==='standard') { const c={window:{}}; vm.runInNewContext(fs.readFileSync(path.join(folder,'content.js'),'utf8'),c,{timeout:1000}); assert(JSON.stringify(c.window.WEEKLY_REPORT)===JSON.stringify(data),`${data.date} 内容未生成，请先 npm run build`); }
  function walk(folder) { for(const entry of fs.readdirSync(folder,{withFileTypes:true})) { if(['.git','node_modules'].includes(entry.name)) continue; const file=path.join(folder,entry.name); if(entry.isDirectory()) walk(file); else if(/\.(?:m?js)$/.test(file)) { const result=spawnSync(process.execPath,['--check',file],{encoding:'utf8'}); assert(result.status===0,result.stderr||`语法检查失败：${file}`); } else if(file.endsWith('.html')) { for(const match of fs.readFileSync(file,'utf8').matchAll(/(?:src|href)="([^"#]+)"/g)) { const ref=match[1].split('?')[0]; if(/^(https?:|#)/.test(ref)||ref.endsWith('/')) continue; asset(ref,path.dirname(file)); } } } }
  // Templates contain paths relative to future report directories, so only inspect actual pages and scripts.
  for(const folder of ['assets','scripts','reports']) walk(path.join(root,folder));
  console.log(`检查通过：${reports.length} 份汇报，脚本、目录及本地媒体引用均有效`);
}
try {
  const [command, date, ...title] = process.argv.slice(2);
  if(command==='new') {
    assert(validDate(date),'用法：npm run new -- YYYY-MM-DD [标题]');
    const folder=path.join(root,'reports',date); assert(!fs.existsSync(folder),'该日期已存在，不会覆盖');
    const data=read(path.join(root,'templates','report.json')); data.date=date; if(title.length) data.title=title.join(' ');
    fs.mkdirSync(folder); fs.mkdirSync(path.join(folder,'media'));
    write(path.join(folder,'media','.gitkeep'),'');
    fs.copyFileSync(path.join(root,'templates','report.html'),path.join(folder,'index.html'));
    write(path.join(folder,'report.json'),JSON.stringify(data,null,2)+'\n');
    build(); console.log(`已新建 reports/${date}/report.json，请填写内容后发布。`);
  } else if(command==='build') build();
  else if(command==='check') check();
  else throw new Error('用法：node scripts/reports.mjs new YYYY-MM-DD [标题] | build | check');
} catch(error) { console.error(error.message); process.exitCode=1; }
